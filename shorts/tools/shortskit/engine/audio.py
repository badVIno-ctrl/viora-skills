"""Sound: SFX from real sample files, voice/music/SFX mix, ducking, loudness to -14 LUFS / -1 dBTP.

2.2 sound policy (no "AI slop"): procedural tones (sine chirps, bells, risers, 808 hits) are never synthesized.
  audio.sfx = "files" (default)  only real recordings from assets/audio/sfx/<name>.(wav|mp3|ogg|flac) play;
                                 events without a file are dropped and listed in manifest.sfx_policy
              "off"              no SFX at all
              "synth"            opt-in drafts: real files first, else noise-only click / whoosh / shutter;
                                 tonal names (tick, pop, riser, hit) still need a file
Built-in music (assets/audio/bed.mp3, edit.mp3) is generated by tools/make_assets.py: a placeholder, never a default.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

import numpy as np

from ..config import asset
from ..util import ShortsError, log, run

SR = 48000
SFX_GAIN_DB = -14.0
SFX_EXT = (".wav", ".mp3", ".ogg", ".flac")
SYNTH_OK = ("click", "whoosh", "shutter")  # noise only: no pitch, nothing that rings
TONAL = ("tick", "pop", "riser", "hit")      # pitched -> sounds synthetic: a real sample file or nothing
SFX_MODES = ("files", "off", "synth")
SYNTHETIC_MUSIC = ("bed.mp3", "edit.mp3")    # own generated placeholders (make_assets.py)


def _env(n: int, attack: float, decay: float) -> np.ndarray:
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-t / max(decay, 1e-4))


def sfx_file(name: str) -> Path | None:
    """A real recording for the event name: assets/audio/sfx/<name>.(wav|mp3|ogg|flac) (see SOURCES.md)."""
    if not re.fullmatch(r"[\w-]+", str(name or "")):
        return None
    for ext in SFX_EXT:
        p = asset(f"audio/sfx/{name}{ext}")
        if p.exists():
            return p
    return None


def synth_sfx(name: str, seed: int = 1) -> np.ndarray:
    """Noise-only drafts: click, whoosh, shutter (opt-in, audio.sfx = "synth"). Tonal sounds are not made."""
    rng = np.random.default_rng(seed)
    if name == "click":
        n = int(0.05 * SR)
        # band-limited noise tick (no sine: a pitched click rings like a bell)
        raw = rng.standard_normal(n)
        hp = np.concatenate([[0.0], np.diff(raw)])
        x = hp * _env(n, 0.0002, 0.004)
    elif name == "whoosh":
        n = int(0.38 * SR)
        noise = rng.standard_normal(n)
        k = np.linspace(0, 1, n)
        out = np.zeros(n)
        y = 0.0
        for i in range(n):  # one-pole low-pass with a cutoff sweep
            a = 0.02 + 0.25 * np.sin(np.pi * k[i]) ** 2
            y += a * (noise[i] - y)
            out[i] = y
        x = out * np.sin(np.pi * k) ** 1.5 * 3
    elif name == "shutter":
        a, b = synth_sfx("click", seed), synth_sfx("click", seed + 1)
        x = np.concatenate([a, np.zeros(int(0.04 * SR)), b * 0.8])
    elif name in TONAL:
        raise ShortsError(f"sfx '{name}' is a pitched sound: it is never synthesized (sounds artificial). "
                          f"Add a real recording assets/audio/sfx/{name}.wav (licence in SOURCES.md) or drop the event")
    else:
        raise ShortsError(f"unknown sfx '{name}': add a real recording assets/audio/sfx/{name}.wav "
                          f"(noise-only drafts exist for {', '.join(SYNTH_OK)} with audio.sfx = \"synth\")")
    x = x / (np.max(np.abs(x)) + 1e-9) * 0.9
    return x.astype(np.float32)


def sfx_clip(name: str, seed: int = 1, allow_synth: bool = False) -> np.ndarray:
    f = sfx_file(name)
    if f is not None:
        return load_audio(f, mono=True)
    if allow_synth and name in SYNTH_OK:
        return synth_sfx(name, seed)
    raise ShortsError(f"no sample file for sfx '{name}' (assets/audio/sfx/{name}.wav)")


def sfx_policy(events: list[tuple[float, str]], audio_cfg: dict | None) -> tuple[list[tuple[float, str]], dict]:
    """Which SFX events really play. Returns (kept, report{mode, kept, dropped[{t,name,why}], synthetic})."""
    cfg = audio_cfg or {}
    mode = str(cfg.get("sfx", "files") or "files").lower()
    if mode in ("none", "false", "0", "no"):
        mode = "off"
    if mode not in SFX_MODES:
        raise ShortsError(f"audio.sfx must be one of {', '.join(SFX_MODES)} (got {mode!r})")
    kept: list[tuple[float, str]] = []
    dropped: list[dict] = []
    synthetic: list[str] = []
    for t, name in events:
        why = None
        if mode == "off":
            why = "audio.sfx = off"
        elif sfx_file(name) is not None:
            pass
        elif mode == "synth" and name in SYNTH_OK:
            synthetic.append(name)
        elif name in TONAL:
            why = "pitched sound, never synthesized: add a real sample file"
        else:
            why = "no sample file in assets/audio/sfx"
        if why:
            dropped.append({"t": round(float(t), 3), "name": name, "why": why})
        else:
            kept.append((float(t), name))
    rep = {"mode": mode, "kept": len(kept), "dropped": dropped, "synthetic": sorted(set(synthetic))}
    if dropped:
        log.info("sfx: %d event(s) dropped (%s)", len(dropped), mode)
    return kept, rep


def music_is_synthetic(path: Path | str | None) -> bool:
    """True for the generated placeholder tracks shipped in assets/audio (bed.mp3, edit.mp3)."""
    if not path:
        return False
    p = Path(str(path))
    try:
        own = p.resolve().parent == asset("audio/bed.mp3").resolve().parent
    except OSError:
        own = False
    return p.name in SYNTHETIC_MUSIC and (own or str(path).startswith("assets/audio/"))


def load_audio(path: Path | str, mono: bool = False, start: float = 0.0, duration: float | None = None) -> np.ndarray:
    cmd = ["ffmpeg", "-loglevel", "error"]
    if start:
        cmd += ["-ss", f"{start:.3f}"]
    cmd += ["-i", str(path)]
    if duration:
        cmd += ["-t", f"{duration:.3f}"]
    cmd += ["-f", "f32le", "-ac", "1" if mono else "2", "-ar", str(SR), "-"]
    p = subprocess.run(cmd, capture_output=True)
    if p.returncode != 0:
        raise ShortsError(f"cannot decode audio {path}: {p.stderr.decode()[-300:]}")
    a = np.frombuffer(p.stdout, np.float32)
    return a if mono else a.reshape(-1, 2)


def lufs(x: np.ndarray) -> float:
    import pyloudnorm as pyln

    if x.ndim == 1:
        x = x[:, None]
    if len(x) < SR * 0.5 or np.max(np.abs(x)) < 1e-6:
        return -70.0
    return float(pyln.Meter(SR).integrated_loudness(x.astype(np.float64)))


def db(v: float) -> float:
    return 10 ** (v / 20)


def regions_envelope(n: int, regions: list[tuple[float, float]], depth_db: float, attack: float = 0.12,
                     release: float = 0.25) -> np.ndarray:
    """Gain curve: 1.0 outside regions, db(depth) inside, with linear ramps."""
    g = np.ones(n, np.float32)
    lo = db(depth_db)
    for s, e in regions:
        a0, a1 = int((s - attack) * SR), int(s * SR)
        r0, r1 = int(e * SR), int((e + release) * SR)
        a0c, r1c = max(0, a0), min(n, r1)
        if a1 > a0c:
            ramp = np.linspace(1, lo, max(1, a1 - a0))[a0c - a0:]
            g[a0c:a1] = np.minimum(g[a0c:a1], ramp[: a1 - a0c])
        g[max(0, a1):min(n, r0)] = lo
        if r1c > r0 >= 0:
            ramp = np.linspace(lo, 1, max(1, r1 - r0))[: r1c - r0]
            g[r0:r1c] = np.minimum(g[r0:r1c], ramp)
    return g


def speech_regions(words: list[dict], gap: float = 0.4) -> list[tuple[float, float]]:
    out: list[list[float]] = []
    for w in sorted(words, key=lambda x: x["s"]):
        if out and w["s"] - out[-1][1] <= gap:
            out[-1][1] = max(out[-1][1], w["e"])
        else:
            out.append([w["s"], w["e"]])
    return [(a, b) for a, b in out]


def post_drop_speech(words: list[dict], drop: float) -> list[tuple[float, float]]:
    """Speech regions that go on after the music drop (clipped to start at the drop)."""
    return [(max(a, drop), b) for a, b in speech_regions(words or []) if b > drop + 0.05]


def place(track: np.ndarray, clip: np.ndarray, t: float, gain: float = 1.0) -> None:
    i = int(t * SR)
    if i >= len(track) or i < 0:
        return
    if clip.ndim == 1 and track.ndim == 2:
        clip = np.repeat(clip[:, None], 2, axis=1)
    n = min(len(clip), len(track) - i)
    track[i:i + n] += clip[:n] * gain


def mix(total: float, voice_parts: list[tuple[float, Path]], src_parts: list[tuple[float, Path]], words: list[dict],
        music: dict | None, music_path: Path | None, sfx: list[tuple[float, str]], out_wav: Path,
        target_lufs: float = -14.0, allow_synth: bool = False) -> dict:
    n = int(total * SR) + 1
    voice = np.zeros((n, 2), np.float32)
    for t, p in voice_parts:
        place(voice, load_audio(p, mono=True), t)
    src = np.zeros((n, 2), np.float32)
    for t, p in src_parts:
        place(src, load_audio(p), t)
    has_voice = np.max(np.abs(voice)) > 1e-4
    report: dict = {"voice": bool(has_voice)}
    mus = np.zeros((n, 2), np.float32)
    music = music or {}
    if music_path:
        m = load_audio(music_path, start=float(music.get("start", 0)))
        if len(m) == 0:
            raise ShortsError(f"music file is empty: {music_path}")
        off = int(float(music.get("offset", 0) or 0) * SR)
        body = max(1, n - off)
        reps = int(np.ceil(body / len(m)))
        m = np.tile(m, (reps, 1))[:body]
        fade_in, fade_out = int((0.3 if music.get("drop_at") is None else 0.6) * SR), int(0.8 * SR)
        m[:fade_in] *= np.linspace(0, 1, min(fade_in, len(m)))[:, None]
        m[-fade_out:] *= np.linspace(1, 0, min(fade_out, len(m)))[:, None]
        if off:
            m = np.concatenate([np.zeros((off, 2), np.float32), m])[:n]
        drop = music.get("drop_at")
        if drop is not None:
            # edit structure (tutorials): dialogue on top, music quiet under it, the drop hits at full level.
            # Level after the drop = loudness of the dialogue (+post_db); before it pre_drop_db under that.
            d = int(float(drop) * SR)
            post = m[d:] if d < n else m
            ref = lufs(voice + src) if (has_voice or np.max(np.abs(src)) > 1e-4) else -14.0
            g_post = ref - lufs(post) + float(music.get("post_db", 0.0))
            pre = float(music.get("pre_drop_db", -16.0))
            env = np.full(n, db(g_post), np.float32)
            ramp = int(0.04 * SR)
            if d > 0:
                env[:d] = db(g_post + pre)
                r0 = max(0, d - ramp)
                env[r0:d] = np.linspace(db(g_post + pre), db(g_post), d - r0)
            after = post_drop_speech(words, float(drop)) if has_voice else []
            if after:
                # 1.3: a voice-over goes on after the drop (letterbox / look keys keyed to it): the voice stays on top,
                # the music ducks under every phrase like without a drop (gain_db under speech, lift between phrases)
                sep = float(music.get("gain_db", -10.0))
                lift = min(abs(float(music.get("duck_db", -10.0))), 6.0)
                env[d:] *= (db(sep + lift) * regions_envelope(n, after, -lift))[d:]
                report.update(post_drop_duck_db=round(sep, 1))
            m = m * env[:, None]
            report.update(drop_at=round(float(drop), 3), music_post_db=round(g_post, 1), pre_drop_db=pre)
        elif has_voice or np.max(np.abs(src)) > 1e-4:
            ref = lufs(voice + src)
            ml = lufs(m)
            sep = float((music or {}).get("gain_db", -10.0))  # music this far under the voice during speech
            gain_db = ref - ml + sep
            duck = float((music or {}).get("duck_db", -10.0))
            lift = min(abs(duck), 6.0)  # between phrases music comes up a little
            regions = speech_regions(words) if words else [(0.0, total)]
            env = regions_envelope(n, regions, -lift)
            m = m * db(gain_db + lift) * env[:, None]
            report.update(music_gain_db=round(gain_db, 1), duck_db=-lift, separation_db=-sep)
        mus = m
    fx = np.zeros((n, 2), np.float32)
    for t, name in sfx:  # already filtered by sfx_policy: files, or noise-only drafts when allowed
        place(fx, sfx_clip(name, seed=int(t * 100) % 97 + 1, allow_synth=allow_synth), t, db(SFX_GAIN_DB))
    mixd = voice + src + mus + fx
    if has_voice and music_path:
        speech_mask = regions_envelope(n, speech_regions(words) if words else [], -60) < 0.5
        if speech_mask.any():
            report["voice_minus_music_db"] = round(lufs(voice[speech_mask]) - lufs(mus[speech_mask]), 1)
    raw = out_wav.with_suffix(".premaster.wav")
    _write_wav(raw, mixd)
    loudnorm(raw, out_wav, target_lufs)
    raw.unlink(missing_ok=True)
    return report


def _write_wav(path: Path, x: np.ndarray) -> None:
    x = np.clip(x, -4, 4).astype(np.float32)
    p = subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "f32le", "-ac", "2", "-ar", str(SR), "-i", "-",
                        "-c:a", "pcm_f32le", str(path)], input=x.tobytes(), capture_output=True)
    if p.returncode != 0:
        raise ShortsError(p.stderr.decode()[-300:])


def loudnorm(src: Path, dst: Path, target: float = -14.0, tp: float = -1.5) -> dict:
    """Two-pass EBU R128 loudnorm (linear when possible)."""
    p = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(src), "-af", f"loudnorm=I={target}:TP={tp}:LRA=11:print_format=json",
                        "-f", "null", "-"], capture_output=True)
    m = re.search(r"\{[^{}]*\"input_i\"[^{}]*\}", p.stderr.decode(errors="replace"))
    if not m:
        run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-af", f"loudnorm=I={target}:TP={tp}:LRA=11", "-ar", SR, dst])
        return {}
    st = json.loads(m.group(0))
    if float(st["input_i"]) < -60:  # silence
        run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-ar", SR, "-c:a", "pcm_s16le", dst])
        return st
    af = (f"loudnorm=I={target}:TP={tp}:LRA=11:measured_I={st['input_i']}:measured_TP={st['input_tp']}:"
          f"measured_LRA={st['input_lra']}:measured_thresh={st['input_thresh']}:offset={st['target_offset']}:linear=true,"
          # safety limiter: punchy edit tracks (808 + hits) came out at -0.7 dBTP after AAC; -2 dB ceiling keeps <= -1
          f"alimiter=limit={10 ** (-2.2 / 20):.3f}:attack=1:release=60:level=disabled")
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-af", af, "-ar", SR, "-c:a", "pcm_s16le", dst])
    log.debug("loudnorm: %s", st)
    return st


def measure(path: Path | str) -> dict:
    """Integrated loudness, true peak, sample peak (for QA)."""
    p = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-af", "ebur128=peak=true,astats=metadata=0",
                        "-f", "null", "-"], capture_output=True)
    err = p.stderr.decode(errors="replace")
    i = re.findall(r"I:\s+(-?[\d.]+|-inf) LUFS", err)
    tp = re.findall(r"Peak:\s+(-?[\d.]+|-inf) dBFS", err)
    pk = re.findall(r"Peak level dB:\s+(-?[\d.]+|-inf)", err)
    clip = re.findall(r"Number of clipped samples:\s+(\d+)", err)  # not printed by every build

    def f(v: list[str]) -> float:
        if not v:
            return float("nan")
        return -99.0 if v[-1] == "-inf" else float(v[-1])

    return {"lufs": f(i), "true_peak": f(tp), "sample_peak": f(pk), "clipped": int(clip[-1]) if clip else None}


def _load_any(path, start: float, duration: float | None):
    """librosa/soundfile cannot open webm/m4a/mp4 (yt-dlp output): decode through ffmpeg to mono 22.05 kHz float."""
    import subprocess

    import librosa

    try:
        if str(path).lower().endswith((".wav", ".flac", ".ogg", ".mp3")):
            return librosa.load(str(path), sr=22050, mono=True, offset=start, duration=duration)
    except Exception:
        pass
    cmd = ["ffmpeg", "-v", "error", "-ss", f"{start:.3f}"] + (["-t", f"{duration:.3f}"] if duration else []) + \
          ["-i", str(path), "-vn", "-ac", "1", "-ar", "22050", "-f", "f32le", "-"]
    raw = subprocess.run(cmd, capture_output=True).stdout
    return np.frombuffer(raw, np.float32).copy(), 22050


def beats(path: Path | str, start: float = 0.0, duration: float | None = None) -> dict:
    """Beat grid and strong beats (librosa). Strong = top 40% onset strength; downbeat phase picked by energy."""
    import librosa

    y, sr = _load_any(path, start, duration)
    if len(y) < sr:
        raise ShortsError("music too short for beat analysis")
    onset = librosa.onset.onset_strength(y=y, sr=sr)
    tempo, bf = librosa.beat.beat_track(onset_envelope=onset, sr=sr, units="frames")
    bt = librosa.frames_to_time(bf, sr=sr)
    st = onset[np.clip(bf, 0, len(onset) - 1)] if len(bf) else np.array([])
    thr = np.quantile(st, 0.6) if len(st) else 0
    strong = [float(t) for t, s in zip(bt, st) if s >= thr]
    phase = int(np.argmax([st[i::4].sum() for i in range(4)])) if len(st) >= 8 else 0
    downs = [float(t) for t in bt[phase::4]]
    rms = librosa.feature.rms(y=y)[0]
    rt = librosa.frames_to_time(np.arange(len(rms)), sr=sr)
    tempo_v = float(np.atleast_1d(tempo)[0])
    return {"tempo": round(tempo_v, 2), "beats": [round(float(t), 3) for t in bt], "strong": [round(t, 3) for t in strong],
            "downbeats": [round(t, 3) for t in downs], "energy": {"t": [round(float(t), 2) for t in rt[::10]],
                                                                  "rms": [round(float(v), 4) for v in rms[::10]]},
            "duration": round(len(y) / sr, 2)}
